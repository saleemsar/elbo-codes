def load(sub=""):
    out = {}
    for s in SCN:
        for t in TASKS:
            p = os.path.join(RES, sub, f"{s}_{t}.json")
            if os.path.exists(p):
                with open(p) as fh:
                    out[(s, t)] = json.load(fh)
    return out


