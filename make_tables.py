PLOS_DPI = 300
PLOS_MAX_W_IN = 7.5  # PLOS: figure width 2.63-7.5 in, height <= 8.75 in


def save(fig, name):
    fig.savefig(os.path.join(FIG, name + ".pdf"), bbox_inches="tight")
    tif = os.path.join(FIG, name + ".tif")
    fig.savefig(tif, dpi=PLOS_DPI, bbox_inches="tight",
                pil_kwargs={"compression": "tiff_lzw"})
    plt.close(fig)
    # bbox_inches="tight" can push the saved width past the figsize, and the Agg
    # backend writes RGBA. PLOS requires RGB/grayscale within 7.5 in, so flatten
    # the alpha channel onto white and scale down if the bounding box overran.
    from PIL import Image
    im = Image.open(tif)
    im.load()
    if im.mode in ("RGBA", "LA", "P"):
        rgba = im.convert("RGBA")
        flat = Image.new("RGB", rgba.size, (255, 255, 255))
        flat.paste(rgba, mask=rgba.split()[-1])
        im = flat
    max_px = int(PLOS_MAX_W_IN * PLOS_DPI)
    if im.size[0] > max_px:
        h = round(im.size[1] * max_px / im.size[0])
        im = im.resize((max_px, h), Image.LANCZOS)
    im.save(tif, compression="tiff_lzw", dpi=(PLOS_DPI, PLOS_DPI))


