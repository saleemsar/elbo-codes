def f4(x):
    return f"{x:.4f}"


def pct(x, d=2):
    return f"{100 * x:.{d}f}"


def i(x):
    return f"{int(x):,}"


def tex(s):
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def write(name, body):
    with open(os.path.join(GEN, name), "w") as fh:
        fh.write("% GENERATED by make_tables.py from results/*.json -- do not edit\n" + body)


def tabular(spec, header, rows):
    out = [r"\begin{tabular}{" + spec + "}", r"\hline", " & ".join(rf"\textbf{{{h}}}" for h in header) + r"\\ \thickhline"]
    out += [" & ".join(str(c) for c in r) + r"\\ \hline" for r in rows]
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def cls(res, tag, name):
    for c in res["test"][tag]["per_class"]:
        if c["class"] == name:
            return c
    raise KeyError(name)


